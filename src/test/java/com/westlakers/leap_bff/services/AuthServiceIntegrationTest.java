package com.westlakers.leap_bff.services;

import com.westlakers.leap_bff.dtos.LoginRequest;
import com.westlakers.leap_bff.dtos.RegisterRequest;
import com.westlakers.leap_bff.dtos.RegisterResponse;
import com.westlakers.leap_bff.entities.UserCredentials;
import com.westlakers.leap_bff.mappers.UserCredentialsMapper;
import com.westlakers.leap_bff.security.JwtService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;

import java.time.LocalDate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

@SpringBootTest
@ActiveProfiles("test")
class AuthServiceIntegrationTest {

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private AuthService authService;

    @Autowired
    private UserCredentialsMapper userCredentialsMapper;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private JwtService jwtService;

    @BeforeEach
    void setUpSchema() {
        jdbcTemplate.execute("CREATE SEQUENCE IF NOT EXISTS users_user_id_seq START WITH 1 INCREMENT BY 1");

        jdbcTemplate.execute(
            "CREATE TABLE IF NOT EXISTS users (" +
                "user_id BIGINT DEFAULT NEXT VALUE FOR users_user_id_seq PRIMARY KEY," +
                "date_of_birth DATE NOT NULL," +
                "first_name VARCHAR(50) NOT NULL," +
                "last_name VARCHAR(50) NOT NULL," +
                "phone_number VARCHAR(20) NOT NULL UNIQUE," +
                "status_id BIGINT NOT NULL," +
                "create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP," +
                "tax_id VARCHAR(20)" +
            ")"
        );

        jdbcTemplate.execute(
            "CREATE TABLE IF NOT EXISTS user_credentials (" +
                "credential_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "user_id BIGINT NOT NULL," +
                "role_id BIGINT NOT NULL," +
                "email VARCHAR(255) UNIQUE NOT NULL," +
                "username VARCHAR(50) UNIQUE NOT NULL," +
                "password_hash VARCHAR(255) NOT NULL," +
                "is_active BOOLEAN DEFAULT TRUE," +
                "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" +
            ")"
        );

        jdbcTemplate.execute("DELETE FROM user_credentials");
        jdbcTemplate.execute("DELETE FROM users");
    }

    @Test
    void registerThenLogin_HappyPath_PersistsAndReturnsValidJwt() {
        RegisterRequest registerRequest = new RegisterRequest();
        registerRequest.setEmail("integration.user@example.com");
        registerRequest.setPassword("StrongPass123!");
        registerRequest.setFirstName("Integration");
        registerRequest.setLastName("User");
        registerRequest.setPhoneNumber("5559876543");
        registerRequest.setTaxId("987654321");
        registerRequest.setDateOfBirth(LocalDate.of(1990, 1, 1));

        RegisterResponse registerResponse = authService.register(registerRequest);
        assertNotNull(registerResponse.getUserId());
        assertEquals("integration.user@example.com", registerResponse.getEmail());

        UserCredentials stored = userCredentialsMapper.findByEmail("integration.user@example.com");
        assertNotNull(stored);
        assertNotNull(stored.getPasswordHash());
        assertTrue(passwordEncoder.matches("StrongPass123!", stored.getPasswordHash()));

        LoginRequest loginRequest = new LoginRequest();
        loginRequest.setEmail("integration.user@example.com");
        loginRequest.setPassword("StrongPass123!");

        String token = authService.authenticateAndIssueToken(loginRequest);
        assertNotNull(token);
        assertTrue(jwtService.validateToken(token));
        assertEquals("integration.user@example.com", jwtService.getEmailFromToken(token));
    }
}